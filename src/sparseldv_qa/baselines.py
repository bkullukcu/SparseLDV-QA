"""Independent QR/POD-style sensor selection references and guarded PySensors adapter.

These in-house functions IMPLEMENT comparable algorithms, but their outputs are
NOT represented as having been generated by the external PySensors package.
Training must exclude every held-out configuration and its resonance windows.
"""
from __future__ import annotations
import numpy as np
from scipy.linalg import qr
from scipy.spatial.distance import cdist


def _matrix(training):
    """Convert complex (sample, point, frequency) to real point-feature matrix."""
    h = np.asarray(training, complex)
    if h.ndim != 3 or min(h.shape) == 0 or not np.isfinite(h).all():
        raise ValueError('training must be finite (sample,point,frequency)')
    norm = np.sqrt(np.mean(np.abs(h)**2, axis=(1, 2), keepdims=True))
    if np.any(norm == 0):
        raise ValueError('zero-energy training scan')
    a = (h / norm).transpose(1, 0, 2).reshape(h.shape[1], -1)
    return np.column_stack([a.real, a.imag])


def qr_pod_points(training, count, n_modes=None):
    """Real-imag POD/SVD basis followed by column-pivoted QR sensor ranking.

    Matches the underlying SVD + pivoted QR principle of PySensors' SSPOR
    examples; NOT a runtime invocation of PySensors. Returns point indices.
    """
    x = _matrix(training)
    n = x.shape[0]
    if not isinstance(count, (int, np.integer)) or not 1 <= count < n:
        raise ValueError('count must be between 1 and n_points-1')
    if n_modes is None:
        n_modes = count
    if not isinstance(n_modes, (int, np.integer)) or not 1 <= n_modes <= min(x.shape):
        raise ValueError('invalid mode count')
    u, _, _ = np.linalg.svd(x, full_matrices=False)
    _, _, pivots = qr(u[:, :n_modes].T, pivoting=True, mode='economic')
    return np.asarray(pivots[:count], int)


def farthest_geometry_points(coordinates, count):
    """Deterministic farthest-point geometry-only sensor selection."""
    xyz = np.asarray(coordinates, float)
    if xyz.ndim != 2 or len(xyz) < 2 or not np.isfinite(xyz).all() or len(np.unique(xyz, axis=0)) != len(xyz):
        raise ValueError('finite, unique point coordinates required')
    if not 1 <= count < len(xyz):
        raise ValueError('invalid count')
    d = cdist(xyz, xyz)
    chosen = [int(np.argmax(np.linalg.norm(xyz - xyz.mean(axis=0), axis=1)))]
    while len(chosen) < count:
        dist = np.min(d[:, chosen], axis=1)
        dist[chosen] = -1
        chosen.append(int(np.argmax(dist)))
    return np.asarray(chosen, int)


def optional_pysensors_points(training, count):
    """Call the actual external PySensors SSPOR/SVD/QR when installed.

    This optional adapter is unavailable unless `pysensors` is installed.
    Report external package version separately when publishing results.
    """
    try:
        import pysensors as ps
    except ImportError as e:
        raise ImportError('Install pysensors to execute actual PySensors; QR/POD in-house baseline is separate') from e
    x = _matrix(training).T  # PySensors: observations x sensor location.
    model = ps.SSPOR(basis=ps.basis.SVD(n_basis_modes=count),
                     optimizer=ps.optimizers.QR(), n_sensors=count)
    model.fit(x)
    out = np.asarray(model.get_selected_sensors(), int)
    if len(out) != count or len(np.unique(out)) != count:
        raise RuntimeError('PySensors returned an invalid selection')
    return out
